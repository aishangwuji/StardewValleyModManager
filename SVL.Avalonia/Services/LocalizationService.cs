    public event Action? LanguageChanged;

    public ObservableCollection<string> SupportedLanguages { get; } = ["zh-CN", "en-US"];

    public string CurrentLanguage { get; private set; } = "zh-CN";

    public LocalizationService(AppUserSettingsStore settingsStore)
    {
        _settingsStore = settingsStore;

        var settings = _settingsStore.Load();
        var language = string.IsNullOrWhiteSpace(settings.UiLanguage) ? "zh-CN" : settings.UiLanguage;
        CurrentLanguage = Catalog.ContainsKey(language) ? language : "zh-CN";
    }

    public string Get(string key)
    {
        if (Catalog.TryGetValue(CurrentLanguage, out var languageMap) &&
            languageMap.TryGetValue(key, out var localizedValue))
        {
            return localizedValue;
        }

        if (Catalog.TryGetValue("zh-CN", out var fallbackMap) &&
            fallbackMap.TryGetValue(key, out var fallbackValue))
        {
            return fallbackValue;
        }

        return key;
    }

    public void SetLanguage(string language)
    {
        if (string.IsNullOrWhiteSpace(language) || !Catalog.ContainsKey(language) ||
            string.Equals(CurrentLanguage, language, StringComparison.OrdinalIgnoreCase))
        {
            return;
        }

        CurrentLanguage = language;

        var settings = _settingsStore.Load();
        settings.UiLanguage = language;
        _settingsStore.Save(settings);

        LanguageChanged?.Invoke();
    }
